"""The client OpenAPI file and its stability rule (CONTRACT-C15 §9.2 item 6, §10.3, A24).

`subset` cuts the operations tagged `client` (and the schemas they reference) out of the app's OpenAPI document;
`tools/gen_docs.py --client-openapi` writes the result to `contracts/openapi-client-v1.json`. `breaking_changes`
lists what a new version of that file removes or narrows compared with an old one:

* a removed operation, parameter, request body or response status;
* a removed field (object property) or enum value, anywhere in a request or response schema;
* a narrowed type (a type the old schema accepted is gone, `null` included);
* a new required parameter, request body or request field;
* a tighter request limit (`maxLength`, `maxItems`, `maximum` lower; `minLength`, `minItems`, `minimum` higher).

Adding operations, optional parameters, fields and enum values is allowed (client-api v1 is additive; clients ignore
unknown members and map unknown values to "other"). An approved break needs a client-api major version: a release
decision, never a silent regeneration.
"""

from __future__ import annotations

import copy
import re
from typing import Any

from . import client_api

HTTP_METHODS = ("get", "put", "post", "delete", "patch", "head", "options")
_REF = re.compile(r"#/components/schemas/(.+)\Z")


def _refs(node: Any, out: set[str]) -> None:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and (m := _REF.match(ref)):
            out.add(m.group(1))
        for value in node.values():
            _refs(value, out)
    elif isinstance(node, list):
        for value in node:
            _refs(value, out)


def subset(spec: dict[str, Any], tag: str = client_api.CLIENT_TAG) -> dict[str, Any]:
    """The operations carrying `tag`, with every schema they reach, as a stand-alone OpenAPI document."""
    paths: dict[str, Any] = {}
    for path, item in sorted(spec.get("paths", {}).items()):
        ops = {m: copy.deepcopy(op) for m, op in item.items() if m in HTTP_METHODS and tag in (op.get("tags") or [])}
        if ops:
            paths[path] = ops
    schemas = spec.get("components", {}).get("schemas", {})
    wanted: set[str] = set()
    _refs(paths, wanted)
    todo = list(wanted)
    while todo:
        name = todo.pop()
        found: set[str] = set()
        _refs(schemas.get(name, {}), found)
        for extra in found - wanted:
            wanted.add(extra)
            todo.append(extra)
    return {
        "openapi": spec.get("openapi", "3.1.0"),
        "info": {"title": "Atlas client API (client-api v1)", "version": client_api.VERSION,
                 "description": ("The subset of Atlas `/api/v2` that external tools are written against "
                                 "(CONTRACT-C15 §9-§10). Generated by `tools/gen_docs.py --client-openapi`; additive "
                                 "within v1: clients ignore unknown members and map unknown vocabulary values to "
                                 "\"other\". Send `Authorization: Bearer <token>` (a personal read token, e.g. from "
                                 "pairing), unless the node lists the `public_read` capability."),
                 "license": {"name": "CC0-1.0", "url": "https://creativecommons.org/publicdomain/zero/1.0/"}},
        "x-client-api": {"version": client_api.VERSION, "min_supported": client_api.MIN_SUPPORTED},
        "paths": paths,
        "components": {"schemas": {name: copy.deepcopy(schemas[name]) for name in sorted(wanted) if name in schemas}},
    }


