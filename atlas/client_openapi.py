def _resolve(spec: dict[str, Any], schema: Any) -> tuple[Any, str | None]:
    if isinstance(schema, dict) and isinstance(schema.get("$ref"), str) and (m := _REF.match(schema["$ref"])):
        return spec.get("components", {}).get("schemas", {}).get(m.group(1), {}), m.group(1)
    return schema, None


def _json_schema(part: Any) -> Any:
    if not isinstance(part, dict):
        return None
    content = part.get("content") or {}
    media = content.get("application/json")
    return media.get("schema") if isinstance(media, dict) else None


class _Diff:
    def __init__(self, old: dict[str, Any], new: dict[str, Any]):
        self.old, self.new = old, new
        self.problems: list[str] = []
        self.seen: set[tuple[str | None, str | None, bool]] = set()

    def add(self, where: str, what: str) -> None:
        self.problems.append(f"{where}: {what}")

    def types(self, spec: dict[str, Any], schema: Any) -> set[str] | None:
        """The JSON types a schema admits; None for "anything"."""
        schema, _ = _resolve(spec, schema)
        if not isinstance(schema, dict):
            return None
        if "anyOf" in schema or "oneOf" in schema:
            out: set[str] = set()
            for member in schema.get("anyOf", []) + schema.get("oneOf", []):
                got = self.types(spec, member)
                if got is None:
                    return None
                out |= got
            return out
        kind = schema.get("type")
        if kind is None:
            if "properties" in schema:
                return {"object"}
            if "enum" in schema or "const" in schema:
                return {type(v).__name__ for v in schema.get("enum", [schema.get("const")])}
            return None
        out = set(kind) if isinstance(kind, list) else {kind}
        if "number" in out:
            out.add("integer")  # a number admits every integer
        return out

    def members(self, spec: dict[str, Any], schema: Any) -> list[Any]:
        schema, _ = _resolve(spec, schema)
        if not isinstance(schema, dict):
            return []
        items = schema.get("anyOf", []) + schema.get("oneOf", [])
        return [m for m in items if not (isinstance(m, dict) and m.get("type") == "null")]

    def compare(self, o: Any, n: Any, where: str, request: bool) -> None:
        o_res, o_name = _resolve(self.old, o)
        n_res, n_name = _resolve(self.new, n)
        key = (o_name, n_name, request)
        if o_name is not None and n_name is not None:
            if key in self.seen:
                return
            self.seen.add(key)
        if not isinstance(o_res, dict) or not isinstance(n_res, dict):
            return
        old_types, new_types = self.types(self.old, o_res), self.types(self.new, n_res)
        if old_types is not None and new_types is not None and not old_types <= new_types:
            self.add(where, f"narrowed type (no longer {', '.join(sorted(old_types - new_types))})")
        o_enum, n_enum = o_res.get("enum"), n_res.get("enum")
        if isinstance(o_enum, list) and isinstance(n_enum, list):
            for value in o_enum:
                if value not in n_enum:
                    self.add(where, f"removed enum value {value!r}")
        elif o_enum is None and isinstance(n_enum, list) and request:
            self.add(where, "narrowed to an enum")
        o_props, n_props = o_res.get("properties") or {}, n_res.get("properties") or {}
        for name, sub in o_props.items():
            if name not in n_props:
                self.add(where, f"removed field {name!r}")
            else:
                self.compare(sub, n_props[name], f"{where}.{name}", request)
        if request:
            for name in sorted(set(n_res.get("required") or []) - set(o_res.get("required") or [])):
                self.add(where, f"new required field {name!r}")
            for limit in ("maxLength", "maxItems", "maximum", "exclusiveMaximum", "maxProperties"):
                if limit in n_res and (limit not in o_res or n_res[limit] < o_res[limit]):
                    self.add(where, f"narrowed {limit} ({o_res.get(limit)} -> {n_res[limit]})")
            for limit in ("minLength", "minItems", "minimum", "exclusiveMinimum", "minProperties"):
                if limit in n_res and (limit not in o_res or n_res[limit] > o_res[limit]):
                    self.add(where, f"narrowed {limit} ({o_res.get(limit)} -> {n_res[limit]})")
            if "pattern" in n_res and n_res.get("pattern") != o_res.get("pattern"):
                self.add(where, "narrowed pattern")
        if "items" in o_res and "items" in n_res:
            self.compare(o_res["items"], n_res["items"], f"{where}[]", request)
        o_add, n_add = o_res.get("additionalProperties"), n_res.get("additionalProperties")
        if isinstance(o_add, dict) and isinstance(n_add, dict):
            self.compare(o_add, n_add, f"{where}{{}}", request)
        o_members, n_members = self.members(self.old, o_res), self.members(self.new, n_res)
        if len(o_members) == 1 and len(n_members) == 1:
            self.compare(o_members[0], n_members[0], where, request)

    def run(self) -> list[str]:
        for path, item in sorted(self.old.get("paths", {}).items()):
            for method, op in sorted(item.items()):
                if method not in HTTP_METHODS:
                    continue
                where = f"{method.upper()} {path}"
                nop = self.new.get("paths", {}).get(path, {}).get(method)
                if nop is None:
                    self.add(where, "removed operation")
                    continue
                self.operation(where, op, nop)
        return self.problems

    def operation(self, where: str, op: dict[str, Any], nop: dict[str, Any]) -> None:
        o_params = {(p["name"], p["in"]): p for p in op.get("parameters", [])}
        n_params = {(p["name"], p["in"]): p for p in nop.get("parameters", [])}
        for key, param in o_params.items():
            if key not in n_params:
                self.add(where, f"removed parameter {key[0]!r}")
            else:
                self.compare(param.get("schema"), n_params[key].get("schema"), f"{where} parameter {key[0]}", True)
        for key, param in n_params.items():
            if param.get("required") and not (key in o_params and o_params[key].get("required")):
                self.add(where, f"new required parameter {key[0]!r}")
        o_body, n_body = op.get("requestBody"), nop.get("requestBody")
        if o_body is not None and n_body is None:
            self.add(where, "removed request body")
        elif o_body is None and n_body is not None and n_body.get("required"):
            self.add(where, "new required request body")
        elif o_body is not None and n_body is not None:
            self.compare(_json_schema(o_body), _json_schema(n_body), f"{where} body", True)
        for code, resp in (op.get("responses") or {}).items():
            n_resp = (nop.get("responses") or {}).get(code)
            if n_resp is None:
                self.add(where, f"removed response {code}")
                continue
            o_schema, n_schema = _json_schema(resp), _json_schema(n_resp)
            if o_schema is not None and n_schema is not None:
                self.compare(o_schema, n_schema, f"{where} response {code}", False)


def breaking_changes(old: dict[str, Any], new: dict[str, Any]) -> list[str]:
    """What `new` removes or narrows compared with `old` (see the module notes); empty when it is additive only."""
    return _Diff(old, new).run()
