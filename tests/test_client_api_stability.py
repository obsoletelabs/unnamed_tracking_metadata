def test_cli_seed_connectors_v1(tmp_path):
    env = {"ATLAS_DATABASE_URL": f"sqlite:///{tmp_path}/seed.db", "ATLAS_ROLE": "local",
           "ATLAS_MEDIA_DIR": str(tmp_path / "media"), "ATLAS_STEAM_ENABLED": "false",
           "PYTHONIOENCODING": "utf-8", "SYSTEMROOT": __import__("os").environ.get("SYSTEMROOT", "")}
    run = lambda *a: subprocess.run([sys.executable, "-m", "atlas.cli", *a], cwd=ROOT, env=env,  # noqa: E731
                                    capture_output=True, text=True, timeout=300)
    assert run("migrate").returncode == 0
    first = run("seed", "--fixture", client_seed.FIXTURE, "--token")
    assert first.returncode == 0, first.stderr
    out = json.loads(first.stdout)
    assert set(out["ids"]) == set(client_seed.NAMES) and out["token"].startswith("atl_")
    assert out["created"] is True
    again = run("seed", "--fixture", client_seed.FIXTURE)
    assert again.returncode == 0, again.stderr
    out2 = json.loads(again.stdout)
    assert out2["ids"] == out["ids"] and out2["created"] is False and "token" not in out2  # idempotent
    bad = run("seed", "--fixture", "nope")
    assert bad.returncode != 0
    import sqlite3

    with sqlite3.connect(tmp_path / "seed.db") as db:  # the CLI token is audited like the admin API's
        rows = db.execute("select action, target from audit_entry where action = 'token_create'").fetchall()
    assert ("token_create", out["token_id"]) in rows


def test_cli_seed_refuses_a_live_database(tmp_path):
    """A24 review: the seed is invented data that enters the change log, so a database holding other records (or an
    authority) is refused unless --force."""
    env = {"ATLAS_DATABASE_URL": f"sqlite:///{tmp_path}/live.db", "ATLAS_ROLE": "local",
           "ATLAS_MEDIA_DIR": str(tmp_path / "media"), "ATLAS_STEAM_ENABLED": "false",
           "PYTHONIOENCODING": "utf-8", "SYSTEMROOT": __import__("os").environ.get("SYSTEMROOT", "")}
    run = lambda *a: subprocess.run([sys.executable, "-m", "atlas.cli", *a], cwd=ROOT, env=env,  # noqa: E731
                                    capture_output=True, text=True, timeout=300)
    assert run("migrate").returncode == 0
    from atlas import main
    from atlas.service import ingest

    from .conftest import batch, build_settings

    app = main.create_app(build_settings(database_url=env["ATLAS_DATABASE_URL"], role="local",
                                         media_dir=env["ATLAS_MEDIA_DIR"]))
    st = app.state.atlas
    with st.maker() as s:
        ingest(s, st.ctx, batch("igdb", [{"external_id": "LIVE-1", "title": "A Real Catalogue Entry"}]), system=True)
        s.commit()
    st.maker.kw["bind"].dispose()
    refused = run("seed", "--fixture", client_seed.FIXTURE)
    assert refused.returncode == 2 and "already holds records" in refused.stderr
    forced = run("seed", "--fixture", client_seed.FIXTURE, "--force")
    assert forced.returncode == 0, forced.stderr
    assert json.loads(forced.stdout)["created"] is True


def test_seed_refuses_an_authority():
    class S:
        role = "authority"

    class Empty:
        def get(self, *a):
            return None

        def scalar(self, *a):
            return None

    assert "authority" in client_seed.refusal(Empty(), S())
    S.role = "local"
    assert client_seed.refusal(Empty(), S()) is None
