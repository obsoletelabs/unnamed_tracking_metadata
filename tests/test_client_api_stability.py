def test_generated_client_openapi_keeps_every_frozen_baseline(generated):
    """§9.2 item 6 against frozen baselines, not the working copy: regenerating the committed file after a break
    must not make this pass. Each baseline is pinned by sha256 in `client_openapi.BASELINES`."""
    baselines = gen_docs.client_baselines()  # raises on a missing, unpinned or edited baseline
    assert client_api.VERSION in baselines or any(
        client_openapi.major(v) == client_openapi.major(client_api.VERSION) for v in baselines), \
        "the current client-api major has no frozen baseline (contracts/client-api-baselines/)"
    assert client_openapi.baseline_breaks(baselines, generated) == []
    committed = json.loads(SPEC_FILE.read_text(encoding="utf-8"))
    assert client_openapi.baseline_breaks(baselines, committed) == []


def test_a_regenerated_break_is_still_caught(generated, monkeypatch, tmp_path):
    """The reviewer's bypass: drop a field, regenerate, commit. The baseline check and the generator both refuse."""
    broken = copy.deepcopy(generated)
    site = broken["components"]["schemas"]["ClientApiInfo"]["properties"]
    site.pop("min_supported")
    problems = client_openapi.baseline_breaks(gen_docs.client_baselines(), broken)
    assert any("removed field" in p and "1.0 baseline" in p for p in problems), problems
    monkeypatch.setattr(gen_docs, "client_openapi", lambda: broken)
    with pytest.raises(SystemExit, match="refusing to write a breaking client OpenAPI"):
        gen_docs.write_client_openapi(tmp_path / "out.json")
    assert not (tmp_path / "out.json").exists()
    # a new major is the only way through: the 1.x baselines stop applying
    assert client_openapi.baseline_breaks(gen_docs.client_baselines(), broken, version="2.0") == []


def test_an_edited_baseline_is_refused(monkeypatch, tmp_path):
    frozen = tmp_path / "openapi-client-1.0.json"
    frozen.write_bytes((gen_docs.CLIENT_BASELINES / "openapi-client-1.0.json").read_bytes() + b" ")
    monkeypatch.setattr(gen_docs, "CLIENT_BASELINES", tmp_path)
    with pytest.raises(SystemExit, match="was edited"):
        gen_docs.client_baselines()
    frozen.unlink()
    with pytest.raises(SystemExit, match="differ from the pinned ones"):
        gen_docs.client_baselines()


def test_committed_client_openapi_is_current(generated):
    committed = json.loads(SPEC_FILE.read_text(encoding="utf-8"))
    assert committed == generated, "client OpenAPI changed: run python tools/gen_docs.py --client-openapi"
    sidecar = SPEC_FILE.with_name(SPEC_FILE.name + ".sha256").read_text(encoding="utf-8").split()
    assert sidecar == [lf_sha256(SPEC_FILE), SPEC_FILE.name]


def test_subset_holds_the_client_routes_only(generated):
    ops = {(m, p) for p, item in generated["paths"].items() for m in item}
    must = {("get", "/api/v2/site"), ("post", "/api/v2/resolve"), ("get", "/api/v2/games"),
            ("get", "/api/v2/games/{cid}"), ("post", "/api/v2/games/batch"), ("get", "/api/v2/games/{cid}/relations"),
            ("get", "/api/v2/games/{cid}/artwork"), ("get", "/api/v2/games/{cid}/achievements"),
            ("get", "/api/v2/artwork/{art_id}/image"), ("get", "/api/v2/media/{digest}"), ("get", "/api/v2/changes"),
            ("post", "/api/v2/client/pair"), ("post", "/api/v2/client/pair/poll"),
            ("get", "/api/v2/records"), ("get", "/api/v2/records/{cid}"), ("post", "/api/v2/records/batch")}
    assert must <= ops
    for gone in ("/api/v2/games/{cid}/explain", "/api/v2/tokens", "/api/v2/sync/changes", "/api/v2/observations",
                 "/api/v2/games/{cid}/merge"):
        assert gone not in generated["paths"]
    for item in generated["paths"].values():
        for op in item.values():
            assert client_api.CLIENT_TAG in op["tags"]
    assert generated["info"]["version"] == client_api.VERSION
    assert generated["x-client-api"] == {"version": client_api.VERSION, "min_supported": client_api.MIN_SUPPORTED}
    # every $ref resolves inside the file, so the subset stands alone
    text = json.dumps(generated)
    for ref in set(__import__("re").findall(r'"#/components/schemas/([^"]+)"', text)):
        assert ref in generated["components"]["schemas"], ref
    # the documented record shape is there, not an empty schema
    record = generated["paths"]["/api/v2/games/{cid}"]["get"]["responses"]["200"]["content"]["application/json"]
    assert record["schema"] == {"$ref": "#/components/schemas/ClientRecord"}


# ---- the stability rules (§9.2 item 6) ----------------------------------------------------------------------------

BASE = {
    "openapi": "3.1.0", "info": {"title": "t", "version": "1.0"},
    "paths": {"/api/v2/x": {"get": {
        "tags": ["read", "client"],
        "parameters": [{"name": "q", "in": "query", "required": False, "schema": {"type": "string", "maxLength": 200}}],
        "responses": {"200": {"content": {"application/json": {"schema": {"$ref": "#/components/schemas/Out"}}}}},
    }, "post": {
        "tags": ["read", "client"],
        "requestBody": {"required": True, "content": {"application/json": {"schema": {"$ref": "#/components/schemas/In"}}}},
        "responses": {"200": {"content": {"application/json": {"schema": {}}}}},
    }}},
    "components": {"schemas": {
        "Out": {"type": "object", "properties": {
            "id": {"type": "string"}, "kind": {"type": "string", "enum": ["a", "b"]},
            "n": {"anyOf": [{"type": "integer"}, {"type": "null"}]},
            "items": {"type": "array", "items": {"$ref": "#/components/schemas/Item"}}}},
        "Item": {"type": "object", "properties": {"name": {"type": "string"}}},
        "In": {"type": "object", "properties": {"ids": {"type": "array", "maxItems": 200, "items": {"type": "string"}}},
               "required": ["ids"]},
    }},
}


def changed(fn) -> list[str]:
    new = copy.deepcopy(BASE)
    fn(new)
    return client_openapi.breaking_changes(BASE, new)


def test_additive_changes_are_not_breaking():
    assert client_openapi.breaking_changes(BASE, BASE) == []
    assert changed(lambda s: s["components"]["schemas"]["Out"]["properties"].update(extra={"type": "string"})) == []
    assert changed(lambda s: s["components"]["schemas"]["Out"]["properties"]["kind"]["enum"].append("c")) == []
    assert changed(lambda s: s["paths"].update({"/api/v2/y": copy.deepcopy(s["paths"]["/api/v2/x"])})) == []
    assert changed(lambda s: s["paths"]["/api/v2/x"]["get"]["parameters"].append(
        {"name": "opt", "in": "query", "required": False, "schema": {"type": "string"}})) == []
    assert changed(lambda s: s["paths"]["/api/v2/x"]["get"]["parameters"][0]["schema"].update(maxLength=300)) == []
    assert changed(lambda s: s["components"]["schemas"]["In"]["properties"]["ids"].update(maxItems=500)) == []


@pytest.mark.parametrize("edit, words", [
    (lambda s: s["paths"].pop("/api/v2/x"), "removed operation"),
    (lambda s: s["paths"]["/api/v2/x"].pop("post"), "removed operation"),
    (lambda s: s["components"]["schemas"]["Out"]["properties"].pop("id"), "removed field"),
    (lambda s: s["components"]["schemas"]["Item"]["properties"].pop("name"), "removed field"),
    (lambda s: s["components"]["schemas"]["Out"]["properties"]["kind"]["enum"].remove("b"), "removed enum value"),
    (lambda s: s["components"]["schemas"]["Out"]["properties"]["n"].update(anyOf=[{"type": "integer"}]),
     "narrowed type"),
    (lambda s: s["components"]["schemas"]["Out"]["properties"]["id"].update(type="integer"), "narrowed type"),
    (lambda s: s["paths"]["/api/v2/x"]["get"]["parameters"].append(
        {"name": "must", "in": "query", "required": True, "schema": {"type": "string"}}), "new required parameter"),
    (lambda s: s["paths"]["/api/v2/x"]["get"]["parameters"][0].update(required=True), "new required parameter"),
    (lambda s: s["paths"]["/api/v2/x"]["get"]["parameters"].pop(), "removed parameter"),
    (lambda s: s["paths"]["/api/v2/x"]["get"]["parameters"][0]["schema"].update(maxLength=100), "narrowed"),
    (lambda s: s["components"]["schemas"]["In"]["properties"]["ids"].update(maxItems=100), "narrowed"),
    (lambda s: s["components"]["schemas"]["In"].update(required=["ids", "more"]), "new required field"),
])
def test_breaking_changes_are_reported(edit, words):
    problems = changed(edit)
    assert problems and any(words in p for p in problems), problems


