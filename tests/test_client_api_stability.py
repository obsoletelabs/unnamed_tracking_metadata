def test_fixture_catalogue_content(exported):
    """3 games, 3 books, 1 series, 1 merge redirect, 1 record of a type clients do not know, forward-compat."""
    load = lambda name: json.loads((exported / name).read_text(encoding="utf-8"))  # noqa: E731
    games = [load(f"games/record-{n}.json") for n in ("lanternfall", "copper-tide", "quiet-orbit")]
    books = [load(f"books/record-{n}.json") for n in ("the-lamp-keeper", "salt-and-signal", "the-far-light")]
    assert [g["media_type"] for g in games] == ["game"] * 3 and [b["media_type"] for b in books] == ["book"] * 3
    assert all(b["authors"] for b in books) and any(b.get("editions") for b in books)
    series = load("books/record-series-lamp-cycle.json")
    assert series["media_type"] == "series" and len(series["relations"]["members"]) == 2
    member = load("books/relations-the-lamp-keeper.json")
    assert any(e.get("position") for e in member["edges"])
    redirected = load("games/record-redirected.json")
    assert redirected["redirected_from"] and redirected["id"] == games[0]["id"]
    unknown = load("games/record-unknown-type.json")
    assert unknown["media_type"] == "comic"  # a media type the connectors do not know (§9.2 item 2)
    fc = load("forward-compat/record-unknown-members.json")
    assert "x_future_member" in fc and any(e.get("format") == "x_future_format" for e in fc["editions"])
    not_applicable = load("books/achievements-the-lamp-keeper.json")
    assert not_applicable["applicable"] is False and not_applicable["results"] == []
    assert load("books/search-isbn.json")["results"][0]["id"] == books[0]["id"]
    manifest = load("MANIFEST.json")
    etags = [e for e in manifest["files"] if e.get("not_modified")]
    assert etags and all(e["response_headers"]["ETag"] for e in etags)
    # synthetic only: no real provider namespaces with real ids, no Open Library data
    text = "\n".join(p.read_text(encoding="utf-8") for p in exported.rglob("*.json"))
    assert "openlibrary.org" not in text and '"steam"' not in text


