"""CONTRACT-C15 §9.2-§9.3 and §10.3 (A24): the client OpenAPI subset, its stability rules and the generated fixtures.

* `contracts/openapi-client-v1.json` is generated from the routes tagged `client` (`tools/gen_docs.py
  --client-openapi`). It must equal what the code generates now, and nothing in it may be removed or narrowed
  (`client_openapi.breaking_changes`) against the frozen, sha256-pinned baselines in
  `contracts/client-api-baselines/` (never against the working copy, which regeneration overwrites); an approved
  break needs a client-api major bump (§9.2 item 6).
* `contracts/client-fixtures/` is generated by `tools/export_client_fixtures.py` from the synthetic
  `connectors-v1` seed (3 games, 3 books, 1 series, 1 merge redirect, 1 record of a type clients do not know) and
  pinned by sha256, in the layout the atlas-connectors repository copies (`contract/fixtures/`).
"""

